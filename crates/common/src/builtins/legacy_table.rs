//! The builtin table as programs up to stored program version 6 were fingerprinted.
//!
//! Those fingerprints cover each used builtin's declared argument counts and types, so a
//! later change to a declaration would make old programs fail to load. They are checked
//! against this frozen copy of the table instead of the live one, and, failing that,
//! against the declarations it replaced since database format 3.0.0. Generated from the
//! table at 772f14ffa; never edit it to follow the live table.

use super::legacy::{
    LegacyArgType::{Any, AnyNum, Typed},
    LegacyCount::{Q, U},
    LegacyDeclaration as D,
};

const fn d(
    id: u16,
    name: &'static str,
    min: super::legacy::LegacyCount,
    max: super::legacy::LegacyCount,
    types: &'static [super::legacy::LegacyArgType],
) -> D {
    D {
        id,
        name,
        min,
        max,
        types,
        implemented: true,
        exposed: true,
    }
}

const fn unimplemented(
    id: u16,
    name: &'static str,
    min: super::legacy::LegacyCount,
    max: super::legacy::LegacyCount,
    types: &'static [super::legacy::LegacyArgType],
) -> D {
    D {
        implemented: false,
        ..d(id, name, min, max, types)
    }
}

